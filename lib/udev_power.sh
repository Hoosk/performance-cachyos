#!/usr/bin/env bash
# Standby Wakeup & PCI Runtime Power Management Module

run_udev_power() {
    log_section "Standby Wakeup & Runtime PM Optimization (udev)"

    local rules_content
    rules_content="# Generated by standby-optimizer for Arch/CachyOS
# Purpose:
#   1. Prevent spurious I2C touchpad & PCIe/USB/Thunderbolt wakeups while lid is closed
#   2. Keep RTC/TAD (ACPI000E / rtc_cmos) and Lid/Power buttons enabled for suspend-then-hibernate
#   3. Enable PCI Runtime Power Management (auto) on auxiliary SoC devices to unlock S0ix / Package C10

# --- Disable spurious wakeup on I2C HID touchpads/keyboards ---
ACTION==\"add|change\", SUBSYSTEM==\"i2c\", DRIVERS==\"i2c_hid_acpi\", ATTR{power/wakeup}=\"disabled\"
"

    # Dynamically detect any currently enabled I2C wakeup devices
    for wpath in /sys/bus/i2c/devices/*/power/wakeup; do
        [[ -f "${wpath}" ]] || continue
        local dev_dir dev_id
        dev_dir="$(dirname "$(dirname "${wpath}")")"
        dev_id="$(basename "${dev_dir}")"
        if [[ "$(cat "${wpath}" 2>/dev/null)" == "enabled" ]]; then
            log_info "Adding udev rule to disable I2C wakeup on ${dev_id}"
            rules_content+="ACTION==\"add|change\", SUBSYSTEM==\"i2c\", KERNEL==\"${dev_id}\", ATTR{power/wakeup}=\"disabled\""$'\n'
        fi
    done

    rules_content+=$'\n'"# --- Disable wakeup on PCIe Root Ports, xHCI USB, and Thunderbolt controllers ---"$'\n'
    for wpath in /sys/bus/pci/devices/*/power/wakeup; do
        [[ -f "${wpath}" ]] || continue
        if [[ "$(cat "${wpath}" 2>/dev/null)" == "enabled" ]]; then
            local dev_dir dev_id class_hex
            dev_dir="$(dirname "$(dirname "${wpath}")")"
            dev_id="$(basename "${dev_dir}")"
            class_hex="$(cat "${dev_dir}/class" 2>/dev/null || printf "")"
            # Match PCI bridges (0x0604xx) and USB/Thunderbolt controllers (0x0c03xx / 0x0c04xx)
            if [[ "${class_hex}" =~ ^0x0604 || "${class_hex}" =~ ^0x0c03 || "${class_hex}" =~ ^0x0c04 ]]; then
                log_info "Adding udev rule to disable PCI wakeup on ${dev_id} ($(lspci -s "${dev_id}" 2>/dev/null || printf "PCI"))"
                rules_content+="ACTION==\"add|change\", SUBSYSTEM==\"pci\", KERNEL==\"${dev_id}\", ATTR{power/wakeup}=\"disabled\""$'\n'
            fi
        fi
    done

    rules_content+=$'\n'"# --- Enable Runtime PM (auto) on PCI devices (excluding NVMe which uses APST/simple-suspend) ---"$'\n'
    rules_content+="ACTION==\"add|change\", SUBSYSTEM==\"pci\", ATTR{class}!=\"0x010802\", ATTR{power/control}=\"auto\""$'\n'

    # Ensure RTC / ACPI Alarm wakeup stays enabled for suspend-then-hibernate
    rules_content+=$'\n'"# --- Explicitly preserve RTC / ACPI Time & Alarm Device wakeup for suspend-then-hibernate ---"$'\n'
    rules_content+="ACTION==\"add|change\", SUBSYSTEM==\"platform\", KERNEL==\"ACPI000E:*\", ATTR{power/wakeup}=\"enabled\""$'\n'
    rules_content+="ACTION==\"add|change\", SUBSYSTEM==\"rtc\", KERNEL==\"rtc0\", ATTR{device/power/wakeup}=\"enabled\""$'\n'

    write_priv_file "${UDEV_RULE_FILE}" "${rules_content}"
    log_ok "Wrote udev standby rules to ${UDEV_RULE_FILE}"

    log_info "Reloading and triggering udev rules..."
    run_priv udevadm control --reload-rules
    run_priv udevadm trigger --subsystem-match=i2c --subsystem-match=pci --subsystem-match=platform

    # Also apply immediately to live sysfs nodes in case udev trigger skips unchanged devices
    for wpath in /sys/bus/i2c/devices/*/power/wakeup; do
        [[ -f "${wpath}" ]] || continue
        if [[ "$(cat "${wpath}" 2>/dev/null)" == "enabled" ]]; then
            run_priv bash -c "echo disabled > '${wpath}'"
        fi
    done

    for wpath in /sys/bus/pci/devices/*/power/wakeup; do
        [[ -f "${wpath}" ]] || continue
        local dev_dir class_hex
        dev_dir="$(dirname "$(dirname "${wpath}")")"
        class_hex="$(cat "${dev_dir}/class" 2>/dev/null || printf "")"
        if [[ "$(cat "${wpath}" 2>/dev/null)" == "enabled" ]] && [[ "${class_hex}" =~ ^0x0604 || "${class_hex}" =~ ^0x0c03 || "${class_hex}" =~ ^0x0c04 ]]; then
            run_priv bash -c "echo disabled > '${wpath}'"
        fi
    done

    for ctrl in /sys/bus/pci/devices/*/power/control; do
        [[ -f "${ctrl}" ]] || continue
        local dev_dir class_hex
        dev_dir="$(dirname "$(dirname "${ctrl}")")"
        class_hex="$(cat "${dev_dir}/class" 2>/dev/null || printf "")"
        # Skip NVMe (0x010802) so kernel NVMe APST & simple-suspend manage it cleanly
        if [[ "${class_hex}" != "0x010802" && "$(cat "${ctrl}" 2>/dev/null)" == "on" ]]; then
            run_priv bash -c "echo auto > '${ctrl}'" || true
        fi
    done

    # Live-enable PCIe ASPM policy if writable
    if [[ -w /sys/module/pcie_aspm/parameters/policy || "${EUID}" -eq 0 || "${DRY_RUN}" == "1" ]]; then
        log_info "Applying live PCIe ASPM policy: powersupersave"
        run_priv bash -c "echo powersupersave > /sys/module/pcie_aspm/parameters/policy" || true
    fi

    log_ok "Live wakeup sources and PCI Runtime PM optimized."
}
