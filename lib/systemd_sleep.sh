#!/usr/bin/env bash
# Systemd Sleep & Logind Configuration Module + S3 (deep) Live Test

run_systemd_sleep() {
    log_section "Systemd Sleep & Lid Switch Configuration"

    local mem_sleep_avail chosen_mode
    mem_sleep_avail="$(cat /sys/power/mem_sleep 2>/dev/null || printf "s2idle")"

    if [[ "${SLEEP_MODE_PREF}" == "deep" ]]; then
        if [[ "${mem_sleep_avail}" == *"deep"* ]]; then
            chosen_mode="deep"
        else
            log_warn "Requested 'deep' (S3), but BIOS only exposes: ${mem_sleep_avail}. Falling back to s2idle."
            chosen_mode="s2idle"
        fi
    elif [[ "${SLEEP_MODE_PREF}" == "s2idle" ]]; then
        chosen_mode="s2idle"
    else
        # auto mode: keep s2idle as default unless user explicitly selects deep, or allow kernel default
        chosen_mode="s2idle"
    fi

    local sleep_conf
    sleep_conf="# Generated by standby-optimizer
[Sleep]
AllowSuspend=yes
AllowHibernation=yes
AllowSuspendThenHibernate=yes
AllowHybridSleep=yes
MemorySleepMode=${chosen_mode}
HibernateDelaySec=${HIBERNATE_DELAY}
HibernateOnACPower=no
"

    local logind_conf
    logind_conf="# Generated by standby-optimizer
[Login]
SleepOperation=suspend-then-hibernate suspend
HandleLidSwitch=suspend-then-hibernate
HandleLidSwitchExternalPower=suspend
HandleLidSwitchDocked=ignore
"

    write_priv_file "${SLEEP_DROPIN_FILE}" "${sleep_conf}"
    log_ok "Wrote systemd-sleep drop-in: ${SLEEP_DROPIN_FILE} (MemorySleepMode=${chosen_mode}, HibernateDelaySec=${HIBERNATE_DELAY})"

    write_priv_file "${LOGIND_DROPIN_FILE}" "${logind_conf}"
    log_ok "Wrote systemd-logind drop-in: ${LOGIND_DROPIN_FILE} (HandleLidSwitch=suspend-then-hibernate)"

    # Apply live /sys/power/mem_sleep
    if [[ "${mem_sleep_avail}" == *"${chosen_mode}"* ]]; then
        log_info "Setting live /sys/power/mem_sleep to '${chosen_mode}'..."
        run_priv bash -c "echo '${chosen_mode}' > /sys/power/mem_sleep"
    fi

    log_info "Reloading systemd manager configuration..."
    run_priv systemctl daemon-reload
    log_ok "Systemd sleep & logind configuration updated."
}

run_test_deep_sleep() {
    log_section "Live Hardware S3 (deep) Suspend Test"
    local mem_sleep_avail
    mem_sleep_avail="$(cat /sys/power/mem_sleep 2>/dev/null || printf "")"
    if [[ "${mem_sleep_avail}" != *"deep"* ]]; then
        log_err "BIOS does not advertise 'deep' (S3) in /sys/power/mem_sleep (${mem_sleep_avail})."
        return 1
    fi

    if ! command -v rtcwake >/dev/null 2>&1; then
        log_err "'rtcwake' utility not found."
        return 1
    fi

    log_info "Switching /sys/power/mem_sleep to 'deep' and suspending for 15 seconds via RTC alarm..."
    run_priv bash -c "echo deep > /sys/power/mem_sleep"
    run_priv rtcwake -m mem -s 15
    log_ok "System resumed from S3 (deep) sleep test! Current /sys/power/mem_sleep: $(cat /sys/power/mem_sleep)"
}
